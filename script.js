let raceRunning = false;


function startRace() {

    if (raceRunning) return;

    if (!car1Select || !car2Select) return;

    raceRunning = true;

    const car1 =
        cars[
            Number(
                car1Select.value
            )
        ];

    const car2 =
        cars[
            Number(
                car2Select.value
            )
        ];

    const distanceType =
        distanceSelect.value;

    const targetDistance =
        raceDistances[
            distanceType
        ] || 400;


    const carElement1 =
        document.querySelector(
            ".race-car.car1"
        );

    const carElement2 =
        document.querySelector(
            ".race-car.car2"
        );


    const track =
        document.querySelector(
            ".race-track"
        );


    const status =
        document.getElementById(
            "raceStatus"
        );

    const winner =
        document.getElementById(
            "raceWinner"
        );


    if (!carElement1 ||
        !carElement2 ||
        !track) {

        raceRunning = false;
        return;

    }


    resetRace();


    const laneName1 =
        document.getElementById(
            "laneName1"
        );

    const laneName2 =
        document.getElementById(
            "laneName2"
        );


    if (laneName1)
        laneName1.textContent =
            car1.name;

    if (laneName2)
        laneName2.textContent =
            car2.name;


    let countdown = 3;

    if (status)
        status.textContent =
            countdown;

    if (winner)
        winner.textContent =
            "GET READY";


    const countdownTimer =
        setInterval(() => {

            countdown--;

            if (countdown > 0) {

                if (status)
                    status.textContent =
                        countdown;

            } else {

                clearInterval(
                    countdownTimer
                );

                if (status)
                    status.textContent =
                        "GO!";

                if (winner)
                    winner.textContent =
                        "RACE IN PROGRESS";


                runRace(
                    car1,
                    car2,
                    targetDistance
                );

            }

        }, 800);

}


/* =========================================================
   RACE ENGINE
   ========================================================= */

function runRace(
    car1,
    car2,
    targetDistance
) {

    const carElement1 =
        document.querySelector(
            ".race-car.car1"
        );

    const carElement2 =
        document.querySelector(
            ".race-car.car2"
        );

    const track =
        document.querySelector(
            ".race-track"
        );


    const startPosition = 25;

    const finishPosition =
        track.clientWidth * 0.88;


    const startTime =
        performance.now();


    let finished1 = false;
    let finished2 = false;

    let finishTime1 = null;
    let finishTime2 = null;


    function frame(now) {

        const elapsed =
            (now - startTime) / 1000;


        /*
           Dezelfde tijd wordt gebruikt
           voor beide auto's.

           Hierdoor heeft de afstand
           geen invloed op acceleratie.
        */

        const speed1 =
            calculateSpeedKmh(
                car1,
                elapsed
            );

        const speed2 =
            calculateSpeedKmh(
                car2,
                elapsed
            );


        const distance1 =
            calculateDistance(
                car1,
                elapsed
            );

        const distance2 =
            calculateDistance(
                car2,
                elapsed
            );


        /*
           Progress is ALLEEN voor de
           positie van het autootje.

           Het verandert de snelheid NIET.
        */

        const progress1 =
            Math.min(
                distance1 /
                targetDistance,
                1
            );

        const progress2 =
            Math.min(
                distance2 /
                targetDistance,
                1
            );


        const position1 =
            startPosition +
            (
                finishPosition -
                startPosition
            ) * progress1;


        const position2 =
            startPosition +
            (
                finishPosition -
                startPosition
            ) * progress2;


        carElement1.style.left =
            position1 + "px";

        carElement2.style.left =
            position2 + "px";


        updateDisplay(
            1,
            car1,
            speed1,
            distance1
        );

        updateDisplay(
            2,
            car2,
            speed2,
            distance2
        );


        if (
            progress1 >= 1 &&
            !finished1
        ) {

            finished1 = true;
            finishTime1 = elapsed;

            showFinish(
                1,
                finishTime1,
                car1
            );

        }


        if (
            progress2 >= 1 &&
            !finished2
        ) {

            finished2 = true;
            finishTime2 = elapsed;

            showFinish(
                2,
                finishTime2,
                car2
            );

        }


        if (
            !finished1 ||
            !finished2
        ) {

            requestAnimationFrame(
                frame
            );

        } else {

            finishRace(
                car1,
                car2,
                finishTime1,
                finishTime2
            );

        }

    }


    requestAnimationFrame(
        frame
    );

}


/* =========================================================
   DISPLAY
   ========================================================= */

function updateDisplay(
    number,
    car,
    speed,
    distance
) {

    const speedElement =
        document.getElementById(
            "speed" + number
        );

    const distanceElement =
        document.getElementById(
            "distance" + number
        );


    if (speedElement) {

        speedElement.textContent =
            convertSpeed(speed);

    }


    if (distanceElement) {

        distanceElement.textContent =
            formatDistance(distance);

    }


    const speedUnitElement =
        document.getElementById(
            "speedUnit" + number
        );

    const distanceUnitElement =
        document.getElementById(
            "distanceUnit" + number
        );


    if (speedUnitElement) {

        speedUnitElement.textContent =
            unitSelect.value === "mph"
                ? "MPH"
                : "KM/H";

    }


    if (distanceUnitElement) {

        distanceUnitElement.textContent =
            unitSelect.value === "mph"
                ? "MI"
                : "KM";

    }

}


/* =========================================================
   UNIT CONVERSIONS
   ========================================================= */

function convertSpeed(kmh) {

    if (
        unitSelect &&
        unitSelect.value === "mph"
    ) {

        return Math.round(
            kmh * 0.621371
        );

    }

    return Math.round(kmh);

}


function formatDistance(meters) {

    let value =
        meters / 1000;


    if (
        unitSelect &&
        unitSelect.value === "mph"
    ) {

        value *=
            0.621371;

    }


    return value.toFixed(2);

}


/* =========================================================
   FINISH
   ========================================================= */

function showFinish(
    number,
    time,
    car
) {

    const timeElement =
        document.getElementById(
            "resultTime" + number
        );

    const topElement =
        document.getElementById(
            "resultTop" + number
        );


    if (timeElement) {

        timeElement.textContent =
            time.toFixed(2) + " s";

    }


    if (topElement) {

        topElement.textContent =
            convertSpeed(car.top)
            + " "
            +
            (
                unitSelect.value === "mph"
                    ? "MPH"
                    : "KM/H"
            );

    }

}


/* =========================================================
   WINNER
   ========================================================= */

function finishRace(
    car1,
    car2,
    time1,
    time2
) {

    const winner =
        document.getElementById(
            "raceWinner"
        );

    const status =
        document.getElementById(
            "raceStatus"
        );


    if (time1 < time2) {

        if (winner)
            winner.textContent =
                car1.name +
                " WINS";

    }

    else if (time2 < time1) {

        if (winner)
            winner.textContent =
                car2.name +
                " WINS";

    }

    else {

        if (winner)
            winner.textContent =
                "PHOTO FINISH";

    }


    if (status)
        status.textContent =
            "FINISHED";


    raceRunning = false;

}


