/* =========================================================
   REALISTISCHE ACCELERATIE
   ========================================================= */

/*
   BELANGRIJK:

   De snelheid wordt NIET gebaseerd op de raceafstand.

   Dus:

   100 meter race
   400 meter race
   2 kilometer race

   gebruiken allemaal exact dezelfde
   acceleratiecurve.

   Alleen het moment waarop de finish
   wordt bereikt verandert.
*/


function calculateAcceleration(car, time) {

    const zero100 =
        car.zero100;

    const zero200 =
        car.zero200;

    const topSpeed =
        car.top / 3.6;


    /* gemiddelde versnelling naar 100 */

    const acceleration100 =
        27.7778 / zero100;


    /*
       Eerste fase:
       sterke acceleratie.
    */

    if (time <= zero100) {

        return Math.min(
            acceleration100 * time,
            27.7778
        );

    }


    /*
       Tweede fase:
       van 100 naar 200.
    */

    const secondPhaseTime =
        zero200 - zero100;


    if (
        time <= zero200 &&
        secondPhaseTime > 0
    ) {

        const progress =
            (time - zero100) /
            secondPhaseTime;

        const smooth =
            1 -
            Math.pow(
                1 - progress,
                1.7
            );

        return (
            27.7778 +
            (55.5556 - 27.7778)
            * smooth
        );

    }


    /*
       Na 200 km/h neemt de
       acceleratie steeds verder af.

       De auto benadert zijn topsnelheid
       maar schiet er nooit overheen.
    */

    const after200 =
        time - zero200;


    const remaining =
        Math.max(
            topSpeed - 55.5556,
            0
        );


    const slowAcceleration =
        1 -
        Math.exp(
            -after200 / 8
        );


    return Math.min(
        55.5556 +
        remaining *
        slowAcceleration,
        topSpeed
    );

}


/* =========================================================
   SNELHEID NAAR KM/H
   ========================================================= */

function calculateSpeedKmh(car, time) {

    const speedMs =
        calculateAcceleration(
            car,
            time
        );

    return speedMs * 3.6;

}


/* =========================================================
   AFSTAND BEREKENEN
   ========================================================= */

function calculateDistance(car, time) {

    /*
       Numerieke integratie.

       Hierdoor wordt afstand bepaald door
       de daadwerkelijke snelheid.

       De raceafstand verandert dus NIET
       de snelheid van de auto.
    */

    const step = 0.02;

    let distance = 0;

    for (
        let t = 0;
        t < time;
        t += step
    ) {

        const speed =
            calculateSpeedKmh(
                car,
                t
            ) / 3.6;

        distance +=
            speed * step;

    }

    return distance;

}


